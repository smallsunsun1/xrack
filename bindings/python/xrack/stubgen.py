"""Generate a typed Python module and its matching .pyi from an XRack file."""

from __future__ import annotations

import argparse
import keyword
import os
from pathlib import Path
from typing import TypeAlias

import xrack

Property: TypeAlias = tuple[str, str, bool]
Callback: TypeAlias = tuple[str, list[str], str | None]
GENERATED = "# Generated by xrack.stubgen."


def identifier(name: str) -> str:
    normalized = name.replace("-", "_")
    if not normalized.isidentifier():
        raise ValueError(f"{name!r} cannot be a Python identifier")
    return normalized + "_" if keyword.iskeyword(normalized) else normalized


def component(
    name: str,
    properties: list[Property],
    callbacks: list[Callback],
    stub: bool,
) -> str:
    class_name = identifier(name)
    methods: list[str] = []
    names = set(dir(xrack.Component)) | {"__init__"}

    def add(member: str, body: list[str]) -> None:
        if member in names:
            raise ValueError(f"{name}: Python member name {member!r} already exists")
        names.add(member)
        methods.extend(body)
        methods.append("")

    initializer = f"super().__init__(xrack.load_file(_SOURCE, live=live, project=project).create({name!r})._instance)"
    methods.extend(
        [
            "    def __init__(self, *, live: bool = False, project: str | PathLike[str] | None = None) -> None:",
            f"        {'...' if stub else initializer}",
            "",
        ]
    )
    for field, ty, writable in properties:
        member = identifier(field)
        getter = f"return cast({ty}, self.get({field!r}))"
        body = [
            "    @property",
            f"    def {member}(self) -> {ty}:",
            f"        {'...' if stub else getter}",
        ]
        if writable:
            setter = f"self.set({field!r}, value)"
            body.extend(
                [
                    "",
                    f"    @{member}.setter",
                    f"    def {member}(self, value: {ty}) -> None:",
                    f"        {'...' if stub else setter}",
                ]
            )
        add(member, body)
    for callback, parameters, result in callbacks:
        member = identifier(callback)
        arguments = [f"arg{index}" for index in range(len(parameters))]
        declared = "".join(f", {arg}: {ty}" for arg, ty in zip(arguments, parameters, strict=True))
        invoked = f"self.invoke({callback!r}" + "".join(f", {arg}" for arg in arguments) + ")"
        call = invoked if result is None else f"return cast({result}, {invoked})"
        handler_result = result or "None | Awaitable[None]"
        add(
            member,
            [
                f"    def {member}(self{declared}) -> {result or 'None'}:",
                f"        {'...' if stub else call}",
            ],
        )
        register = f"self.on({callback!r}, handler)"
        add(
            f"on_{member}",
            [
                f"    def on_{member}(self, handler: Callable[[{', '.join(parameters)}], {handler_result}]) -> None:",
                f"        {'...' if stub else register}",
            ],
        )
    return f"class {class_name}(xrack.Component):\n" + "\n".join(methods)


def generate(source: Path, output: Path) -> tuple[Path, Path]:
    if output.suffix not in {".py", ".pyi"}:
        raise ValueError("The output must have a .py or .pyi suffix")
    source = source.resolve()
    output.parent.mkdir(parents=True, exist_ok=True)
    runtime = output.with_suffix(".py")
    stub = output.with_suffix(".pyi")
    program = xrack.load_file(source)
    components: list[tuple[str, list[Property], list[Callback]]] = []
    names: set[str] = set()
    for name in program.components():
        member = identifier(name)
        if member in names:
            raise ValueError(f"Duplicate Python component name {member!r}")
        names.add(member)
        instance = program.create(name)
        components.append((name, instance._instance.properties(), instance._instance.callbacks()))

    relative_source = os.path.relpath(source, output.parent.resolve())
    header = (
        GENERATED + "\nfrom __future__ import annotations\n\n"
        "from collections.abc import Awaitable, Callable\n"
        "from os import PathLike\n"
        "from pathlib import Path\n"
        "from typing import cast\n\n"
        "import xrack\n\n"
    )
    source_line = f"_SOURCE = Path(__file__).parent / {relative_source!r}\n\n\n"
    generated = {
        runtime: header
        + source_line
        + "\n\n".join(component(*entry, False) for entry in components),
        stub: header + "\n".join(component(*entry, True) for entry in components),
    }
    for path in generated:
        if path.exists() and not path.read_text(encoding="utf-8").startswith(GENERATED + "\n"):
            raise ValueError(f"Refusing to overwrite {path}")
    for path, code in generated.items():
        path.write_text(code.rstrip() + "\n", encoding="utf-8")
    return runtime, stub


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("-o", "--output", type=Path, required=True)
    args = parser.parse_args()
    for path in generate(args.source, args.output):
        print(path)


if __name__ == "__main__":
    main()
