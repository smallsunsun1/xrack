//! Cargo-facing API for XRack applications.
pub use xrack_assets as assets;
#[cfg(feature = "interpreter")]
pub use xrack_interpreter as interpreter;
pub use xrack_layout as layout;
pub use xrack_platform_winit as platform;
#[cfg(target_os = "android")]
pub use xrack_platform_winit::{AndroidDirectory, AndroidDocument};
pub use xrack_platform_winit::{
    Desktop, DesktopTray, DesktopWindow, LocalTask, SpawnLocalError, TaskCancelled, spawn_local,
};
#[cfg(target_os = "ios")]
pub use xrack_platform_winit::{IosDirectory, IosPhotoSelection, IosPhotoThumbnail};
#[cfg(not(feature = "interpreter"))]
pub use xrack_platform_winit::{run, run_desktop};

#[cfg(feature = "interpreter")]
pub fn run<C: xrack_runtime::Component + 'static>(component: C) -> Result<(), String> {
    xrack_interpreter::install_external_loader();
    xrack_platform_winit::run(component)
}

#[cfg(feature = "interpreter")]
pub fn run_desktop(setup: impl FnOnce(&Desktop) -> Result<(), String>) -> Result<(), String> {
    xrack_interpreter::install_external_loader();
    xrack_platform_winit::run_desktop(setup)
}

pub use xrack_renderer_femtovg as renderer;
pub use xrack_runtime as runtime;
pub use xrack_runtime::*;

#[doc(hidden)]
pub mod __live {
    #[cfg(feature = "live-reload")]
    pub use xrack_interpreter::live::*;
}

/// Enable media sessions on the current thread for a custom host.
#[cfg(feature = "media")]
pub use xrack_platform_winit::install_media;
#[cfg(feature = "media")]
pub use xrack_platform_winit::voice;

/// Include the UI generated by `xrack_build::compile` from the application's build script.
#[macro_export]
macro_rules! include_modules {
    () => {
        #[allow(unused_imports)]
        use $crate::__live as __xrack_live;
        #[doc(hidden)]
        use $crate::runtime as __xrack_runtime;
        include!(concat!(env!("OUT_DIR"), "/xrack_ui.rs"));
    };
}
